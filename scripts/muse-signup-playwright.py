#!/usr/bin/env python3
"""Create a Muse account on muse.ai in desktop Chrome via Playwright.

Runs on a GitHub Actions runner (ubuntu-latest) under xvfb-run, headed
Chromium -- no emulator, no adb, no screen coordinates. All interaction is
through DOM selectors.

Temp mail is temp-mail.org (NOT temp.tf): its inbox stays active. The
address is generated by the site -- no provider selection, use whatever
domain it gives.

Flow:
  1. temp-mail.org: dismiss any cookie/consent banner, read the generated
     temporary address. Screenshot step1-temp.png.
  2. muse.ai in a new tab: fill "Mobile number or email", click Continue.
     Screenshots step2-form.png (before) and step3-after-continue.png.
  3. Wait up to 60 s for the next step. If a verification code is asked
     for, fetch it from the temp-mail.org inbox: check for up to 5
     minutes, every ~15 s, accepting mail from any sender, scanning only
     actual message rows for a 6-digit code. If a code is found, enter it
     without clicking the hidden field; if a verification link is found
     instead, open it in the muse.ai tab. If a name is asked for, enter
     "Muse". If no mail arrives after 5 minutes, generate a fresh address
     and resubmit once (max 2 addresses).
  4. STOP (screenshot step4-verify.png, log the reason, do not proceed) if
     a phone number, a payment card, a captcha/Turnstile, or a rejected
     temp email is asked for.

Run #4 change: temp-mail.org replaces temp.tf (Daniel: temp.tf inboxes do
not stay active). No provider selection; the inbox is refreshed with the
site's Refresh button (page reload as fallback); a fresh address comes
from the site's Delete button (cookies cleared as fallback).

Outputs (all under /tmp, uploaded as the muse-signup-desktop artifact):
  muse-account.txt, step1-temp.png, step2-form.png,
  step3-after-continue.png, step4-verify.png

The account is for Muse (the assistant): the name entered is "Muse".

The script never raises out of main: every failure is logged, a screenshot
is taken, and it exits 0 so the workflow still uploads the artifacts.
"""

import re
import time
from playwright.sync_api import sync_playwright

TMP = "/tmp"
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
CODE6_RE = re.compile(r"(?<![0-9])([0-9]{6})(?![0-9])")
PHONE_WORDS = ("phone verification", "verify your phone", "enter your phone",
                "sms code", "texted you", "phone number")
CARD_WORDS = ("payment", "card number", "credit card", "debit card",
              "add a card")
CAPTCHA_WORDS = ("captcha", "turnstile", "verify you are human",
                 "not a robot")
REJECTED_WORDS = ("disposable", "not accepted", "try a different email",
                  "invalid email", "cannot use this email")
CODE_WORDS = ("verification code", "enter the code", "check your email",
              "check your inbox", "we sent", "sent you a code")
SUCCESS_WORDS = ("welcome", "account created", "get started",
                 "your account is ready", "dashboard")


def log(msg):
    print("[muse-signup-desktop] " + str(msg), flush=True)


def shot(page, name):
    path = TMP + "/" + name
    log("screenshot -> " + path)
    try:
        page.screenshot(path=path)
    except Exception as exc:
        log("screenshot EXC: %r" % (exc,))


def body_text(page):
    try:
        return page.inner_text("body")
    except Exception:
        return ""


def find_email(text, domain=None):
    for m in EMAIL_RE.finditer(text):
        if domain is None or m.group(0).lower().endswith("@" + domain):
            return m.group(0)
    return None


def strip_chrome(text):
    """Remove page-chrome counters so a site-wide number can never pass
    as a verification code (run #2 matched a "TOTAL RECEIVED 8064064"
    counter on temp.tf)."""
    text = re.sub(r"total received\s+[0-9,]+\s+messages", "", text, flags=re.I)
    text = re.sub(r"total available.*?addresses", "", text, flags=re.I)
    return text


def find_code6(text):
    """A 6-digit verification code only. A wider digit fallback matched a
    site counter in run #2, so it is not used."""
    m = CODE6_RE.search(text)
    return m.group(1) if m else None


def inbox_rows_text(page):
    """Text of actual inbox message rows only (no page chrome).
    Returns (text, count): the joined subject/sender text of the message
    rows found, and how many rows there were. Rows that only say the
    inbox is empty are not counted.
    """
    for sel in ("tbody tr", "[class*='inbox-item' i]", "[class*='mail-item' i]",
                "[class*='message-item' i]", "[class*='email-item' i]",
                "[role='row']"):
        try:
            rows = page.locator(sel).all()
        except Exception:
            continue
        texts = []
        for row in rows:
            try:
                t = row.inner_text() or ""
            except Exception:
                continue
            low = t.lower()
            if not t.strip():
                continue
            if ("no mail found" in low or "inbox is empty" in low or
                    "no messages" in low or "there are no messages" in low):
                continue
            texts.append(t)
        if texts:
            return "\n".join(texts), len(texts)
    return "", 0


def locate_in_frames(page, make):
    """Try make(frame) on the page and each child frame; return the first
    locator with matches, else None."""
    for frame in page.frames:
        try:
            loc = make(frame)
            if loc.count():
                return loc
        except Exception:
            continue
    return None


def dismiss_cookie_banner(page):
    """Dismiss temp-mail.org's cookie/consent banner, if one is showing.
    Tries the common button labels first, then any button containing
    'Accept'."""
    for label in ("Accept", "Accept all", "I agree", "Agree", "Got it",
                  "Allow", "Accept cookies"):
        try:
            btn = page.get_by_role("button", name=label, exact=True).first
            if btn.count():
                btn.click(timeout=5000)
                log("cookie banner dismissed with %r" % label)
                return True
        except Exception:
            continue
    try:
        btn = page.locator("button", has_text="Accept").first
        if btn.count():
            btn.click(timeout=5000)
            log("cookie banner dismissed via Accept button")
            return True
    except Exception:
        pass
    log("no cookie banner found (or it could not be dismissed)")
    return False


def read_temp_address(page):
    """The temporary address shown on temp-mail.org, or None. The address
    sits in a readonly input (usually #mail); fall back to scanning all
    inputs, then the page text."""
    for sel in ("#mail", "input[readonly]", "input"):
        try:
            for inp in page.locator(sel).all():
                try:
                    val = inp.input_value() or ""
                except Exception:
                    continue
                m = EMAIL_RE.search(val)
                if m:
                    return m.group(0)
        except Exception:
            continue
    return find_email(body_text(page))


def temp_mail_address(page):
    """Open temp-mail.org and read the generated address. No provider
    selection: temp-mail.org gives one address with its own domain, so
    use whatever domain it gives."""
    page.goto("https://temp-mail.org/", wait_until="domcontentloaded",
              timeout=60000)
    page.wait_for_timeout(5000)
    log("temp-mail.org title: " + page.title())
    dismiss_cookie_banner(page)
    email = None
    for attempt in range(3):
        email = read_temp_address(page)
        if email:
            break
        log("address not readable yet, waiting (attempt %d)" % (attempt + 1))
        page.wait_for_timeout(3000)
    if email:
        log("temp-mail.org address: " + email)
    else:
        log("no address readable on temp-mail.org yet")
    return email


def fresh_address(page):
    """Generate a fresh address on temp-mail.org and read it. Clicking
    the site's Delete button makes a new address; if the address is
    unchanged afterwards, clear the site's cookies/storage and reload so
    a brand-new one is generated. Returns the address shown afterwards
    (which may be the old one if nothing changed it)."""
    old = read_temp_address(page)
    page.goto("https://temp-mail.org/", wait_until="domcontentloaded",
              timeout=60000)
    page.wait_for_timeout(4000)
    dismiss_cookie_banner(page)
    try:
        btn = page.get_by_role("button", name="Delete", exact=True).first
        if btn.count():
            btn.click(timeout=10000)
            log("Delete clicked to generate a fresh address")
            page.wait_for_timeout(4000)
    except Exception as exc:
        log("Delete click EXC: %r" % (exc,))
    email = read_temp_address(page)
    if email and email != old:
        log("fresh temp-mail.org address: %s (was %s)" % (email, old))
        return email
    log("Delete did not change the address, clearing cookies and reloading")
    try:
        page.context.clear_cookies()
        page.evaluate("localStorage.clear(); sessionStorage.clear();")
    except Exception as exc:
        log("storage clear EXC: %r" % (exc,))
    try:
        page.reload(wait_until="domcontentloaded", timeout=60000)
        page.wait_for_timeout(5000)
    except Exception as exc:
        log("reload EXC: %r" % (exc,))
    dismiss_cookie_banner(page)
    email = None
    for attempt in range(3):
        email = read_temp_address(page)
        if email and email != old:
            break
        page.wait_for_timeout(3000)
    if email:
        log("fresh temp-mail.org address: %s (was %s)" % (email, old))
    else:
        log("no fresh address readable (old was %s)" % old)
    return email


def refresh_inbox(page):
    """Refresh the temp-mail.org inbox: click the site's Refresh button
    if there is one, else reload the page. Returns True when a refresh
    was attempted."""
    try:
        btn = page.get_by_role("button", name="Refresh", exact=True).first
        if btn.count():
            btn.click(timeout=10000)
            log("inbox refreshed via Refresh button")
            return True
    except Exception as exc:
        log("Refresh click EXC: %r" % (exc,))
    try:
        page.reload(wait_until="domcontentloaded", timeout=60000)
        log("inbox refreshed via page reload")
        return True
    except Exception as exc:
        log("inbox reload EXC: %r" % (exc,))
    return False


def find_link(page, text):
    """A verification link inside the given message text (or an anchor on
    the page) that points back at muse.ai or at a verify endpoint."""
    for m in re.finditer(r"https?://[^\s\"'<>]+muse\.ai[^\s\"'<>]*", text):
        return m.group(0)
    for m in re.finditer(r"https?://[^\s\"'<>]+verify[^\s\"'<>]*", text):
        return m.group(0)
    return None


def open_newest_message(page):
    """Open the first inbox message row. Returns True if one was clicked."""
    for sel in ("tbody tr", "[class*='inbox-item' i]", "[class*='mail-item' i]",
                "[class*='message-item' i]", "[class*='email-item' i]",
                "[role='row']"):
        try:
            rows = page.locator(sel).all()
        except Exception:
            continue
        for row in rows:
            try:
                t = row.inner_text() or ""
            except Exception:
                continue
            if not t.strip():
                continue
            low = t.lower()
            if ("no mail found" in low or "inbox is empty" in low or
                    "no messages" in low or "there are no messages" in low):
                continue
            try:
                row.click(timeout=10000)
                log("opened inbox message: " + t[:120].replace("\n", " | "))
                return True
            except Exception as exc:
                log("open message EXC: %r" % (exc,))
                return False
        if rows:
            return False
    return False


def fetch_code(temp_page, email):
    """Fetch the Muse verification code (or a verification link) from the
    temp-mail.org inbox. Checks for up to 5 minutes, every ~15 s, and
    accepts mail from ANY sender. Only real message rows and opened
    message bodies are scanned -- never page counters. Returns
    (value, kind) where kind is "code" or "link", or (None, None)."""
    temp_page.bring_to_front()
    temp_page.wait_for_timeout(2000)
    log("waiting for mail in the temp-mail.org inbox for " + email)
    deadline = time.time() + 300
    check = 0
    while time.time() < deadline:
        check += 1
        refresh_inbox(temp_page)
        temp_page.wait_for_timeout(4000)
        text = body_text(temp_page)
        rows_text, n = inbox_rows_text(temp_page)
        if n:
            log("inbox check %d: %d message row(s) present" % (check, n))
            scanned = strip_chrome(rows_text)
        elif any(w in text.lower() for w in ("inbox is empty", "no messages",
                                             "there are no messages",
                                             "no mail")):
            log("inbox check %d: empty, no mail for this address" % check)
            temp_page.wait_for_timeout(11000)
            continue
        else:
            log("inbox check %d: no message rows found, scanning cleaned page text" % check)
            scanned = strip_chrome(text)
        code = find_code6(scanned)
        if code:
            log("code found in the inbox list")
            return code, "code"
        link = find_link(temp_page, scanned)
        if link:
            log("verification link found in the inbox list: " + link)
            return link, "link"
        if open_newest_message(temp_page):
            temp_page.wait_for_timeout(3000)
            opened = strip_chrome(body_text(temp_page))
            code = find_code6(opened)
            if code:
                log("code found in the opened message")
                return code, "code"
            link = find_link(temp_page, opened)
            if link:
                log("verification link found in the opened message: " + link)
                return link, "link"
            log("opened message has no code or link")
        temp_page.wait_for_timeout(11000)
    log("no verification code or link arrived in 5 minutes")
    return None, None


def click_button(page, names):
    """Click the first visible, enabled button whose label matches one of
    the given names (exact first, then substring). Returns True if one was
    clicked."""
    for name in names:
        try:
            btn = page.get_by_role("button", name=name, exact=True).first
            if btn.count():
                btn.click(timeout=10000)
                log("clicked button %r" % name)
                return True
        except Exception:
            continue
    for name in names:
        try:
            btn = page.get_by_role("button", name=name, exact=False).first
            if btn.count():
                btn.click(timeout=10000)
                log("clicked button (substring) %r" % name)
                return True
        except Exception:
            continue
    return False


def fill_email(muse_page, email):
    """Fill the 'Mobile number or email' field on muse.ai. Tries the
    aria label first, then other selectors. Returns True when filled."""
    loc = locate_in_frames(
        muse_page,
        lambda f: f.locator(
            "input[aria-label*='Mobile number or email' i], "
            "input[aria-label*='email' i], "
            "input[placeholder*='email' i], "
            "input[type='email'], "
            "input[type='tel'], "
            "input[inputmode='email']"))
    if loc is None:
        return False
    for frame in muse_page.frames:
        try:
            loc.fill(email, timeout=10000)
            return True
        except Exception:
            continue
    try:
        loc.fill(email, force=True, timeout=10000)
        return True
    except Exception as exc:
        log("fill email EXC: %r" % (exc,))
        return False


def handle_name(page):
    """If a name is asked for, enter 'Muse'. Returns True when a name
    field was filled."""
    loc = locate_in_frames(
        page,
        lambda f: f.locator(
            "input[aria-label*='name' i], "
            "input[placeholder*='name' i], "
            "input[name*='name' i]"))
    if loc is None:
        return False
    try:
        loc.fill("Muse", timeout=10000)
        log("name field filled with 'Muse'")
        return True
    except Exception:
        return False


def classify(page):
    """Classify the current muse.ai screen. Returns one of: code, phone,
    card, captcha, rejected, success, name, code-ok, other."""
    low = body_text(page).lower()
    if any(w in low for w in PHONE_WORDS):
        return "phone"
    if any(w in low for w in CARD_WORDS):
        return "card"
    if any(w in low for w in CAPTCHA_WORDS):
        return "captcha"
    if any(w in low for w in REJECTED_WORDS):
        return "rejected"
    loc = locate_in_frames(
        page,
        lambda f: f.locator("input[aria-label*='security code' i], "
                            "input[autocomplete='one-time-code']"))
    if loc is not None:
        return "code"
    if any(w in low for w in CODE_WORDS):
        return "code"
    if any(w in low for w in SUCCESS_WORDS):
        return "success"
    if ("name" in low and "enter" in low) or "what should we call you" in low:
        return "name"
    if "code" in low and "verified" in low:
        return "code-ok"
    return "other"


def wait_next_step(page, timeout_s=60):
    """Wait up to timeout_s for the form to give way to the next step, then
    classify the new screen. Returns (state, waited_seconds)."""
    waited = 0
    while waited < timeout_s:
        state = classify(page)
        if state != "other":
            return state, waited
        page.wait_for_timeout(2000)
        waited += 2
    state = classify(page)
    log("wait_next_step timed out, state=%s" % state)
    return state, waited


def enter_code(page, code):
    """Enter the code WITHOUT clicking the hidden field first. Tries, in
    order: force fill, plain fill, JavaScript value-set with native
    input/change events, typing into the visible OTP container. Verifies
    via input_value after each attempt. Returns True when the value stuck."""
    for frame in page.frames:
        try:
            inp = frame.locator(
                "input[aria-label*='security code' i], "
                "input[autocomplete='one-time-code']").first
            if not inp.count():
                continue
            for method in ("fill", "force-fill", "js-set"):
                try:
                    if method == "fill":
                        inp.fill(code, timeout=5000)
                    elif method == "force-fill":
                        inp.fill(code, force=True, timeout=5000)
                    else:
                        handle = inp.element_handle(timeout=5000)
                        frame.evaluate(
                            "(el, val) => {"
                            " const setter = Object.getOwnPropertyDescriptor("
                            " window.HTMLInputElement.prototype, 'value').set;"
                            " setter.call(el, val);"
                            " el.dispatchEvent(new Event('input', {bubbles: true}));"
                            " el.dispatchEvent(new Event('change', {bubbles: true}));"
                            " }", handle, code)
                    val = inp.input_value() or ""
                    log("code field filled via %s, value now %r" % (method, val))
                    if val == code:
                        return True
                except Exception as exc:
                    log("code fill %s EXC: %r" % (method, exc,))
            try:
                inp.click(timeout=5000, force=True)
                inp.type(code, delay=100)
                val = inp.input_value() or ""
                log("code typed into the OTP container, value now %r" % val)
                if val == code:
                    return True
            except Exception as exc:
                log("code type EXC: %r" % (exc,))
        except Exception:
            continue
    log("could not fill the code field by any method")
    return False


def save_account(email, outcome, page, code_value=None):
    with open(TMP + "/muse-account.txt", "w") as f:
        f.write("temp email: " + email + "\n")
        f.write("outcome: " + outcome + "\n")
        if code_value:
            f.write("verification code: " + code_value + "\n")
    log("account file written")


def run_signup(browser, context, temp_page, muse_page):
    """Two address attempts at most. Returns the outcome string."""
    for email_attempt in (1, 2):
        log("=== address attempt %d of 2 ===" % email_attempt)
        try:
            if email_attempt == 1:
                email = temp_mail_address(temp_page)
            else:
                email = fresh_address(temp_page)
        except Exception as exc:
            log("temp-mail.org step EXC: %r" % (exc,))
            shot(temp_page, "step1-temp.png")
            return "STOP: temp-mail.org could not be loaded"
        if not email:
            shot(temp_page, "step1-temp.png")
            return "STOP: no temp-mail.org address found"
        log("TEMP EMAIL (attempt %d): %s" % (email_attempt, email))
        shot(temp_page, "step1-temp.png")
        try:
            muse_page.goto("https://muse.ai/", wait_until="domcontentloaded",
                            timeout=60000)
            muse_page.wait_for_timeout(5000)
        except Exception as exc:
            log("muse.ai load EXC: %r" % (exc,))
            shot(muse_page, "step2-form.png")
            return "STOP: muse.ai did not load"
        log("muse.ai title: " + muse_page.title())
        log("muse.ai url: " + muse_page.url)
        if not fill_email(muse_page, email):
            shot(muse_page, "step2-form.png")
            return "STOP: email field not found on muse.ai"
        log("email field filled with " + email)
        shot(muse_page, "step2-form.png")
        if not click_button(muse_page, ("Continue", "Next")):
            shot(muse_page, "step3-after-continue.png")
            return "STOP: Continue button not found on muse.ai"
        log("Continue clicked")
        muse_page.wait_for_timeout(2000)
        shot(muse_page, "step3-after-continue.png")
        state, waited = wait_next_step(muse_page)
        log("next step after %ds: %s" % (waited, state))
        shot(muse_page, "step4-verify.png")
        for rnd in (1, 2):
            log("round %d: state=%s" % (rnd, state))
            if state == "phone":
                return "STOP: phone number asked for"
            if state == "card":
                return "STOP: payment card asked for"
            if state == "captcha":
                return "STOP: captcha/Turnstile shown"
            if state == "rejected":
                return "STOP: temp email rejected"
            if state in ("success", "code-ok"):
                save_account(email, "ACCOUNT CREATED (apparent)", muse_page)
                return "ACCOUNT CREATED (apparent)"
            if state == "name":
                if handle_name(muse_page):
                    click_button(muse_page, ("Continue", "Next", "Save"))
                    muse_page.wait_for_timeout(3000)
                    state, _ = wait_next_step(muse_page)
                    shot(muse_page, "step4-verify.png")
                    continue
                return "STOP: name step could not be completed"
            if state == "code":
                log("round %d: switching to temp-mail.org to wait for the code" % rnd)
                value, kind = fetch_code(temp_page, email)
                log("round %d: temp-mail.org fetch done: %s" % (rnd, kind or "nothing"))
                if not value:
                    break
                if kind == "link":
                    muse_page.bring_to_front()
                    try:
                        muse_page.goto(value, wait_until="domcontentloaded",
                                       timeout=60000)
                        muse_page.wait_for_timeout(5000)
                    except Exception as exc:
                        log("verification link open EXC: %r" % (exc,))
                    state, _ = wait_next_step(muse_page)
                    shot(muse_page, "step4-verify.png")
                    continue
                if not enter_code(muse_page, value):
                    shot(muse_page, "step4-verify.png")
                    return "STOP: could not enter the verification code"
                log("code entered, submitting")
                click_button(muse_page, ("Continue", "Verify", "Next", "Submit"))
                muse_page.wait_for_timeout(3000)
                state, _ = wait_next_step(muse_page)
                shot(muse_page, "step4-verify.png")
                continue
            log("unrecognised state %r, stopping" % state)
            return "STOP: unrecognised state after Continue: " + state
        if email_attempt == 1:
            log("trying a fresh temp-mail.org address (attempt 2 of 2)")
            continue
        return "STOP: no verification code arrived"


def main():
    log("=== muse-signup-desktop start ===")
    outcome = "STOP: playwright did not start"
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(headless=False, args=["--no-sandbox"])
            context = browser.new_context(viewport={"width": 1280, "height": 800})
            temp_page = context.new_page()
            muse_page = context.new_page()
            try:
                outcome = run_signup(browser, context, temp_page, muse_page)
            except Exception as exc:
                log("run EXC: %r" % (exc,))
                outcome = "STOP: script error: %r" % (exc,)
                try:
                    shot(muse_page, "step4-verify.png")
                except Exception:
                    pass
            browser.close()
    except Exception as exc:
        log("playwright EXC: %r" % (exc,))
        outcome = "STOP: playwright error: %r" % (exc,)
    log("OUTCOME: " + outcome)
    log("=== muse-signup-desktop end ===")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
